import assert from 'node:assert/strict';
import {placeAtCharacter,copyChordLines,characterCount} from './eqe-chord-positions.mjs';
const base={lines:{0:'DO'},words:{'0:1':'SOL'},positions:{'0':[{offset:2,chord:'LA'}]},intro:'INTRO',references:[{id:3}]};
const original=JSON.stringify(base);
assert.equal(characterCount(' A  B '),6);
assert.equal(characterCount('a😀b'),3);
assert.deepEqual(placeAtCharacter(base,0,1,'RE',' A  B ').positions['0'].map(x=>x.offset),[1,2]);
assert.equal(placeAtCharacter(base,0,2,'',' A  B ').positions['0'],undefined);
assert.throws(()=>placeAtCharacter(base,0,8,'DO',' A  B '),RangeError);
const changed=copyChordLines(base,0,1,2,['abc','def','ghi','jkl']);
assert.equal(changed.lines[2],'DO');
assert.equal(changed.words['2:1'],'SOL');
assert.equal(changed.positions['2'][0].offset,2);
assert.equal(changed.intro,'INTRO');
assert.deepEqual(changed.references,base.references);
assert.throws(()=>copyChordLines(base,0,1,0,['a','b'],false),/DESTINATION_HAS_CHORDS/);
const overlapped=copyChordLines({...base,lines:{0:'DO',1:'RE'}},0,2,1,['abc','def','ghi'],true);
assert.equal(overlapped.lines[1],'DO');
assert.equal(overlapped.lines[2],'RE');
assert.equal(JSON.stringify(base),original,'original must never change');
assert.throws(()=>copyChordLines(base,0,1,2,['abc','def','x'],true),/DESTINATION_POSITION_OUT_OF_RANGE/);
assert.equal(JSON.stringify(base),original,'failed paste must not mutate original');
assert.equal(placeAtCharacter(base,0,0,'DO','').positions['0'][0].offset,0);
assert.throws(()=>placeAtCharacter(base,0,1,'DO',''),RangeError);
const blank=copyChordLines({positions:{'0':[{offset:0,chord:'DO'}]}},0,1,1,['',''],false);
assert.deepEqual(blank.positions['1'],[{offset:0,chord:'DO'}]);
console.log('EQE chord module: baseline and empty-line regression assertions passed');
